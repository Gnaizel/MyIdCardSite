package ru.gnaizel.service.guestbook;

import ru.gnaizel.model.guestbook.Message;

/**
 * Куда уходит сообщение сразу после сохранения.
 * <p>
 * Реализации нет намеренно: сюда подключается отправка в телеграм. Достаточно
 * создать класс с {@code @Service}, который реализует этот интерфейс — сервис
 * заберёт его сам, никакой регистрации не нужно. Пока реализации нет,
 * уведомления просто не отправляются, на приём сообщений это не влияет.
 * <p>
 * Исключение отсюда гасится и только пишется в лог: сообщение уже лежит
 * в базе, и падение телеграма не должно превращаться в ошибку у гостя.
 */
public interface MessageNotifier {
    void onNewMessage(Message message);
}
